#ifndef MADEIRA_NATIVE_CALL_BRIDGE_H
#define MADEIRA_NATIVE_CALL_BRIDGE_H

/* ARM64EC check-call ABI: target in x11, result in x11. The resolver uses
 * AAPCS64; preserve every argument register and full SIMD register contents. */
static __attribute__((naked, noinline, used)) void madeira_native_call_checker(void)
{
    __asm__ volatile(
        "sub sp, sp, #640\n"
        "stp x29, x30, [sp]\n"
        "stp x0, x1, [sp, #16]\n"
        "stp x2, x3, [sp, #32]\n"
        "stp x4, x5, [sp, #48]\n"
        "stp x6, x7, [sp, #64]\n"
        "stp x8, x10, [sp, #80]\n"
        "stp x12, x13, [sp, #96]\n"
        "stp x14, x15, [sp, #112]\n"
        "stp q0, q1, [sp, #128]\n"
        "stp q2, q3, [sp, #160]\n"
        "stp q4, q5, [sp, #192]\n"
        "stp q6, q7, [sp, #224]\n"
        "stp q8, q9, [sp, #256]\n"
        "stp q10, q11, [sp, #288]\n"
        "stp q12, q13, [sp, #320]\n"
        "stp q14, q15, [sp, #352]\n"
        "stp q16, q17, [sp, #384]\n"
        "stp q18, q19, [sp, #416]\n"
        "stp q20, q21, [sp, #448]\n"
        "stp q22, q23, [sp, #480]\n"
        "stp q24, q25, [sp, #512]\n"
        "stp q26, q27, [sp, #544]\n"
        "stp q28, q29, [sp, #576]\n"
        "stp q30, q31, [sp, #608]\n"
        "mov x0, x11\n"
        "bl _ios_fex_native_call_target\n"
        "mov x11, x0\n"
        "ldp q0, q1, [sp, #128]\n"
        "ldp q2, q3, [sp, #160]\n"
        "ldp q4, q5, [sp, #192]\n"
        "ldp q6, q7, [sp, #224]\n"
        "ldp q8, q9, [sp, #256]\n"
        "ldp q10, q11, [sp, #288]\n"
        "ldp q12, q13, [sp, #320]\n"
        "ldp q14, q15, [sp, #352]\n"
        "ldp q16, q17, [sp, #384]\n"
        "ldp q18, q19, [sp, #416]\n"
        "ldp q20, q21, [sp, #448]\n"
        "ldp q22, q23, [sp, #480]\n"
        "ldp q24, q25, [sp, #512]\n"
        "ldp q26, q27, [sp, #544]\n"
        "ldp q28, q29, [sp, #576]\n"
        "ldp q30, q31, [sp, #608]\n"
        "ldp x0, x1, [sp, #16]\n"
        "ldp x2, x3, [sp, #32]\n"
        "ldp x4, x5, [sp, #48]\n"
        "ldp x6, x7, [sp, #64]\n"
        "ldp x8, x10, [sp, #80]\n"
        "ldp x12, x13, [sp, #96]\n"
        "ldp x14, x15, [sp, #112]\n"
        "ldp x29, x30, [sp]\n"
        "add sp, sp, #640\n"
        "ret\n");
}
#endif
